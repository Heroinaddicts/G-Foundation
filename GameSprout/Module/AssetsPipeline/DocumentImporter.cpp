bool References(AssetImportJob & job,const Json::Value & value) {
    if (value.isObject()) {
        if (value.isMember("Guid") && value.isMember("LocalID")) {
            if (!value["Guid"].isString() || !Guid(value["Guid"].asString()).IsValid()
                || !value["LocalID"].isUInt64() || value["LocalID"].asUInt64()==0) return job.Fail("Invalid resource reference");
            const std::string guid=value["Guid"].asString();
            if (guid!=job.Request.GuidString) {
                const auto path=job.Request.SourcePaths.find(guid);
                if (path==job.Request.SourcePaths.end()) return job.Fail("Referenced asset GUID is missing: "+guid);
                if (!job.AddDependency(path->second)) return false;
            }
        }
        for (const auto & child : value) if (!References(job,child)) return false;
    } else if (value.isArray()) for (const auto & child : value) if (!References(job,child)) return false;
    return true;
}

bool MaterialValues(AssetImportJob & job, Json::Value & document) {
    if (document.isMember("ExternalMaterial")) return job.Fail("ExternalMaterial aliases are generated by ModelImporter, not authored in .mat sources");
    std::string error;
    if (!MaterialDefinition::ShaderReference(document,error)) return job.Fail(error);
    Json::Value schema;
    if (!document.isMember("Shader") || document["Shader"].isString()) schema=MaterialDefinition::PreviewSchema();
    else {
        const Json::Value & shader=document["Shader"];
        const auto source=job.Request.SourcePaths.find(shader["Guid"].asString());
        if (source==job.Request.SourcePaths.end()) return job.Fail("Material Shader source GUID is missing");
        if (QFileInfo(QString::fromStdString(source->second)).suffix().compare("shader",Qt::CaseInsensitive)!=0)
            return job.Fail("Material Shader reference must point to a .shader source");
        QByteArray bytes;
        if (!job.AddDependency(source->second,&bytes)) return false;
        if (!MaterialDefinition::ParseShaderSchema(bytes,schema,error)) return job.Fail(error);
        // Workers read source snapshots and never query the main-thread Library.
        const QString metaPath=QDir(QString::fromStdString(job.Request.AssetsRoot))
            .filePath(QString::fromStdString(source->second)+".meta");
        if (!QFileInfo::exists(metaPath)) return job.Fail("Material Shader Meta is missing; its identity cannot be verified");
        {
            QByteArray metaBytes;
            std::string hash;
            Json::Value meta;
            if (!job.ReadFile(metaPath.toStdString(),&metaBytes,hash)
                || !AssetArtifactIO::Parse(metaBytes.toStdString(),meta) || !meta.isObject()
                || !meta["ImportSettings"].isObject()) return job.Fail("Cannot read material Shader Meta");
            if (!meta["Guid"].isString() || meta["Guid"].asString()!=shader["Guid"].asString())
                return job.Fail("Material Shader source Meta GUID does not match its reference");
            if (meta["ImporterType"]=="ComputeShader" || meta["ImportSettings"]["Stage"]=="Compute")
                return job.Fail("A compute Shader cannot be used as a material Shader");
            if (meta["ImporterType"]!="Shader") return job.Fail("Material reference is not imported by the graphics Shader importer");
            const Json::Value stage=meta["ImportSettings"].get("Stage","Vertex");
            if (stage!="Vertex" && stage!="Fragment") return job.Fail("Material Shader must use a graphics Shader stage");
            bool identityFound=false;
            if (meta["SubAssets"].isArray()) for (const auto & identity : meta["SubAssets"]) {
                if (identity.isObject() && identity["LocalID"].isUInt64() && identity["Type"].isUInt()
                    && identity["LocalID"].asUInt64()==shader["LocalID"].asUInt64()
                    && identity["Type"].asUInt()==static_cast<uint16_t>(eAssetType::Shader)) identityFound=true;
            }
            if (!identityFound) return job.Fail("Material Shader LocalID does not identify a graphics Shader");
        }
    }
    if (!MaterialDefinition::NormalizeValues(schema,document,error)) return job.Fail(error);
    for (const auto & property : schema["Properties"]) {
        if (property["Type"]!="Texture") continue;
        const std::string name=property["Name"].asString();
        const Json::Value & texture=document[name];
        if (texture.isNull()) continue;
        const std::string guid=texture["Guid"].asString();
        const auto source=job.Request.SourcePaths.find(guid);
        if (source==job.Request.SourcePaths.end())
            return job.Fail("Material texture parameter '"+name+"' references missing source GUID "+guid);
        const std::string prefix="Material texture parameter '"+name+"' (source '"+source->second+"'): ";
        if (guid==job.Request.GuidString) return job.Fail(prefix+"a .mat source does not contain Texture resources");
        // Texture children may belong to PNGs or to models with embedded images.
        // The resource identity/type decides validity, not the source suffix.
        if (!job.AddDependency(source->second)) return job.Fail(prefix+job.Result.Error);
        const QString metaPath=QDir(QString::fromStdString(job.Request.AssetsRoot))
            .filePath(QString::fromStdString(source->second)+".meta");
        if (!QFileInfo::exists(metaPath)) return job.Fail(prefix+"Meta is missing; the Texture identity cannot be verified");
        QByteArray metaBytes;
        std::string hash;
        Json::Value meta;
        if (!job.ReadFile(metaPath.toStdString(),&metaBytes,hash)
            || !AssetArtifactIO::Parse(metaBytes.toStdString(),meta) || !meta.isObject())
            return job.Fail(prefix+"cannot read resource Meta");
        if (!meta["Guid"].isString() || meta["Guid"].asString()!=guid)
            return job.Fail(prefix+"Meta GUID does not match the texture reference");
        bool identityFound=false;
        if (meta["SubAssets"].isArray()) for (const auto & identity : meta["SubAssets"]) {
            if (identity.isObject() && identity["LocalID"].isUInt64() && identity["Type"].isUInt()
                && identity["LocalID"].asUInt64()==texture["LocalID"].asUInt64()
                && identity["Type"].asUInt()==static_cast<uint16_t>(eAssetType::Texture)) identityFound=true;
        }
        if (!identityFound) return job.Fail(prefix+"LocalID "+std::to_string(texture["LocalID"].asUInt64())+" does not identify a Texture");
    }
    return true;
}

bool Decode(AssetImportJob & job,QByteArray bytes,QByteArray & output) {
    const std::string encoding=job.Settings.get("Encoding","Auto").asString();
    if (encoding=="Binary") {output=bytes;return true;}
    QStringConverter::Encoding format=QStringConverter::Utf8;
    if (encoding=="UTF16LE") format=QStringConverter::Utf16LE;
    else if (encoding=="UTF16BE") format=QStringConverter::Utf16BE;
    else if (encoding=="Auto") {
        if (bytes.startsWith("\xff\xfe")) format=QStringConverter::Utf16LE;
        else if (bytes.startsWith("\xfe\xff")) format=QStringConverter::Utf16BE;
    } else if (encoding!="UTF8") return job.Fail("Unsupported text encoding");
    QStringDecoder decoder(format);
    QString text=decoder(bytes);
    if (decoder.hasError()) return job.Fail("Invalid text encoding");
    if (job.Settings.get("StripByteOrderMark",true).asBool() && !text.isEmpty() && text.front()==QChar(0xfeff)) text.remove(0,1);
    if (job.Settings.get("NormalizeLineEndings",true).asBool()) text.replace("\r\n","\n").replace('\r','\n');
    output=text.toUtf8();return true;
}

bool Includes(AssetImportJob & job,const std::string & path,const QByteArray & source,std::set<std::string> & seen) {
    const QRegularExpression expression(R"include(^\s*#\s*include\s*"([^"]+)"\s*$)include",QRegularExpression::MultilineOption);
    auto matches=expression.globalMatch(QString::fromUtf8(source));
    while (matches.hasNext()) {
        const QString dependency=QDir(QFileInfo(QString::fromStdString(path)).path()).filePath(matches.next().captured(1));
        const std::string relative=QDir::cleanPath(dependency).toStdString();
        if (!seen.insert(relative).second) continue;
        QByteArray bytes;
        if (!job.AddDependency(relative,&bytes) || !Includes(job,relative,bytes,seen)) return false;
    }
    return true;
}
